class Command(BaseCommand):
    help = "Populate the exercise catalog with gym and calisthenics exercises."

    def handle(self, *args, **options):
        created_count = 0
        updated_count = 0
        skipped_count = 0

        for muscle_group, exercises in CATALOG.items():
            for name, equipment in exercises:
                note = f"Equipment: {equipment}"

                existing = ExerciseList.objects.filter(
                    name=name
                ).first()

                if existing is None:
                    ExerciseList.objects.create(
                        name=name,
                        muscle_group=muscle_group,
                        note=note,
                    )
                    created_count += 1
                    continue

                changed = False

                if existing.muscle_group != muscle_group:
                    existing.muscle_group = muscle_group
                    changed = True

                if existing.note != note:
                    existing.note = note
                    changed = True

                if changed:
                    existing.save(
                        update_fields=[
                            "muscle_group",
                            "note",
                        ]
                    )
                    updated_count += 1
                else:
                    skipped_count += 1

        total = sum(
            len(exercises)
            for exercises in CATALOG.values()
        )

        self.stdout.write(
            self.style.SUCCESS(
                "Exercise catalog populated successfully.\n"
                f"Seed entries: {total}\n"
                f"Created: {created_count}\n"
                f"Updated: {updated_count}\n"
                f"Already up to date: {skipped_count}"
            )
        )
